-- ---------- Tabel ----------
create table if not exists public.checks (
  user_id uuid not null references auth.users(id) on delete cascade,
  check_key text not null,
  done boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (user_id, check_key)
);

create table if not exists public.study_days (
  user_id uuid not null references auth.users(id) on delete cascade,
  day date not null,
  primary key (user_id, day)
);

create table if not exists public.words (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  english text not null,
  meaning text not null,
  created_at timestamptz default now()
);

create table if not exists public.notes (
  user_id uuid not null references auth.users(id) on delete cascade primary key,
  content text,
  updated_at timestamptz default now()
);

create table if not exists public.history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  happened_at timestamptz default now(),
  text text
);

create table if not exists public.quiz_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score int,
  total int,
  writing text,
  created_at timestamptz default now()
);

-- ---------- Index ----------
create index if not exists words_user_id_idx on public.words (user_id);
create index if not exists history_user_happened_idx on public.history (user_id, happened_at desc);
create index if not exists quiz_user_created_idx on public.quiz_results (user_id, created_at desc);

