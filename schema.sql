-- ---------- Fungsi migrasi state lama ----------
create or replace function public.import_legacy_state(payload jsonb)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  uid uuid;
  k text;
  d date;
begin
  uid := auth.uid();
  if uid is null then
    raise exception 'Harus login sebelum mengimpor data';
  end if;

  -- tolak bila user sudah punya data (hindari duplikasi)
  if exists (select 1 from public.checks where user_id = uid)
     or exists (select 1 from public.words where user_id = uid)
     or exists (select 1 from public.study_days where user_id = uid)
     or exists (select 1 from public.history where user_id = uid)
     or exists (select 1 from public.quiz_results where user_id = uid)
     or exists (select 1 from public.notes where user_id = uid and coalesce(btrim(content), '') <> '') then
    return false;
  end if;

  -- checks: key harus diawali stage/lesson/week/daily, maks 80 karakter
  for k in
    select je.key
    from jsonb_each_text(coalesce(payload -> 'checks', '{}'::jsonb)) je
    where je.key ~ '^(stage|lesson|week|daily):'
      and length(je.key) <= 80
  loop
    insert into public.checks (user_id, check_key, done)
    values (uid, k, true)
    on conflict do nothing;
  end loop;

  -- study_days: array tanggal 'YYYY-MM-DD' valid
  for d in
    select je.value::date
    from jsonb_array_elements_text(coalesce(payload -> 'study_days', '[]'::jsonb)) je
    where je.value ~ '^\d{4}-\d{2}-\d{2}$'
  loop
    insert into public.study_days (user_id, day)
    values (uid, d)
    on conflict do nothing;
  end loop;

  -- words: skip kosong, batasi panjang
  insert into public.words (user_id, english, meaning)
  select uid, btrim(je ->> 'english'), btrim(je ->> 'meaning')
  from jsonb_array_elements(coalesce(payload -> 'words', '[]'::jsonb)) je
  where coalesce(btrim(je ->> 'english'), '') <> ''
    and coalesce(btrim(je ->> 'meaning'), '') <> ''
    and length(btrim(je ->> 'english')) <= 190
    and length(btrim(je ->> 'meaning')) <= 250;

  -- notes: non-kosong, maks 10000
  if coalesce(payload ->> 'notes', '') <> ''
     and length(payload ->> 'notes') <= 10000 then
    insert into public.notes (user_id, content)
    values (uid, payload ->> 'notes')
    on conflict (user_id) do update
      set content = excluded.content, updated_at = now()
      where coalesce(btrim(notes.content), '') = '';
  end if;

  -- history: happened_at dari data lama (fallback now), text maks 250
  insert into public.history (user_id, happened_at, text)
  select uid,
    case when (je ->> 'happened_at') ~ '^\d{4}-\d{2}-\d{2}'
      then (je ->> 'happened_at')::timestamptz
      else now() end,
    left(je ->> 'text', 250)
  from jsonb_array_elements(coalesce(payload -> 'history', '[]'::jsonb)) je;

  return true;
end;
$$;

revoke execute on function public.import_legacy_state(jsonb) from public, anon;
grant execute on function public.import_legacy_state(jsonb) to authenticated;
